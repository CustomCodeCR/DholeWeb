import assert from 'node:assert/strict'
import test from 'node:test'
import { readFileSync } from 'node:fs'
import { incotermSectionApplicability } from '../src/modules/pricing/utils/pricingIncotermPerspective.ts'

const read = (path: string) => readFileSync(new URL('../' + path, import.meta.url), 'utf8')
const wizard = read('src/modules/pricing/components/PricingAlternativeWizardCrystal.vue')
const fclTransform = read('build/pricingWizardMixedFclFreightFix.ts')

test('FOB export FCL freight is counterparty cost; FOB import and CIF export are customer-side', () => {
  assert.equal(incotermSectionApplicability('Export', 'FOB', 'international_freight'), 'other-party')
  assert.equal(incotermSectionApplicability('Import', 'FOB', 'international_freight'), 'client')
  assert.equal(incotermSectionApplicability('Export', 'CIF', 'international_freight'), 'client')
  assert.equal(incotermSectionApplicability('Export', 'FOB', 'destination_charges'), 'other-party')
  assert.equal(incotermSectionApplicability('Export', 'FOB', 'origin_charges'), 'client')
})

test('P7 recognizes freight:<container> generated by the system, even when legacy code says manual', () => {
  assert.match(wizard, /const generatedEquipmentFreight = line\.costDetailType === 'Freight'/)
  assert.match(wizard, /line\.key === 'freight' \|\| line\.key\.startsWith\('freight:'\)/)
  assert.match(wizard, /\(line\.manual && !generatedEquipmentFreight\)/)
  assert.match(wizard, /if \(props\.rateId \|\| editingRate\.value \|\| line\.detailId/)
  assert.match(wizard, /line\.included = false/)
  assert.match(wizard, /line\.section === section\s*&& line\.included/)
})

test('FCL source prices stay untouched but out-of-term new freight starts unquoted', () => {
  assert.match(fclTransform, /const freightOutsideClientIncoterm = incotermSectionApplicability/)
  assert.match(fclTransform, /operationType\.value, selectedIncotermCode\.value, 'international_freight'/)
  assert.match(fclTransform, /outsideIncotermScopeKey\(\{ key: 'freight:' \+ allocation\.containerTypeId \} as RateLine\)/)
  assert.match(fclTransform, /included: matching\?\.detailId \|\| editingRate\.value \|\| props\.rateId/)
  assert.ok(fclTransform.includes(': !freightOutsideClientIncoterm || freightAcceptedByAgreement'))
  assert.ok(fclTransform.includes('manual: matching?.detailId ? (matching.manual ?? true) : false'))
  assert.ok(fclTransform.includes('costAmount: number(allocation.freightCostAmount)'))
  assert.ok(fclTransform.includes('saleAmount: number(allocation.freightSaleAmount)'))
  assert.ok(fclTransform.includes('quantityOverride: allocation.quantity'))
  assert.doesNotMatch(fclTransform, /included: true,\\n      optional: false,\\n      manual: matching\?\.manual \?\? true/)
})

test('outside Incoterm exception requires P7 action and cannot leak across route/client', () => {
  assert.match(wizard, /function quoteOutsideIncotermByAgreement\(line: RateLine\)/)
  assert.match(wizard, /rememberExplicitOutsideIncoterm\(line, true\)/)
  assert.match(wizard, /outsideIncotermScopeKey\(line\)/)
  assert.match(wizard, /activeCostContextKey\(\), operationType\.value, selectedIncotermCode\.value/)
  assert.match(wizard, /explicitlyQuotedOutsideIncoterm\.value = new Set\(\)/)
  assert.match(wizard, /v-for="candidate in outsideIncotermCandidateLines\(group\.key\)"/)
  assert.match(wizard, /Agregar servicio fuera del Incoterm/)
  assert.match(wizard, /No se incluye automáticamente/)
})
