import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'

const source = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8')

test('Trámites is the single entry point for manual creation and searchable cases', () => {
  const cases = source('src/modules/operations/views/OperationsCasesView.vue')
  const modal = source('src/modules/operations/views/OperationsManualCreateView.vue')
  const router = source('src/core/router/index.ts')
  assert.match(cases, /name: 'operations-case-create'/)
  assert.match(cases, /<DhDrawer/)
  assert.match(cases, /operationsApi\.cases\(page\.value/)
  assert.match(cases, /Buscar IDTRA, QUO o modalidad/)
  assert.match(cases, /accountId: accountId\.value/)
  assert.match(cases, /Abrir expediente completo/)
  assert.match(modal, /operationsApi\.crmAccounts/)
  assert.match(modal, /operationsApi\.createContext/)
  assert.match(modal, /operationsApi\.createAperture/)
  assert.doesNotMatch(modal, /executiveUserId:|blankUser/)
  assert.match(router, /path: 'operations\/cases\/:id'/)
  assert.match(router, /redirect: \{ name: 'operations-cases' \}/)
})
test('full IDTRA uses eight tabs, backend ACL and version-controlled edits', () => {
  const details = source('src/modules/operations/views/OperationsCaseDetailView.vue')
  const api = source('src/modules/operations/services/operationsApi.ts')
  const validation = source('src/modules/operations/components/OperationsApertureValidationPanel.vue')
  for (const tab of ['RESUMEN','QUO','COORDINACION_ORIGEN','DOCUMENTACION','TRANSITO','PANAMA','COSTA_RICA','FINANZAS'])
    assert.ok(details.includes(`code: '${tab}'`), tab)
  assert.match(details, /:disabled="level\(tab\.code\) === 'LOCKED'/)
  assert.match(details, /operationsApi\.caseTabs/)
  assert.match(details, /operationsApi\.caseWorkspace/)
  assert.match(details, /operationsApi\.updateCase/)
  assert.match(details, /operationsApi\.caseInternalNotes/)
  assert.match(details, /<OperationsApertureValidationPanel/)
  assert.match(details, /serverChangedWhileEditing/)
  assert.match(validation, /operationsApi\.decide/)
  assert.match(api, /\/api\/operations\/cases\/\$\{id\}\/commercial\/costs/)
})
test('Operations SignalR client reconnects, joins only an authorized case and fetches REST', () => {
  const realtime = source('src/modules/operations/composables/useOperationsCaseRealtime.ts')
  const details = source('src/modules/operations/views/OperationsCaseDetailView.vue')
  assert.match(realtime, /JoinCase/)
  assert.match(realtime, /ensureValidAccessToken/)
  assert.match(realtime, /onScopeDispose/)
  assert.match(realtime, /operationsChanged/)
  assert.match(realtime, /onInvalidated\(id\)/)
  assert.match(details, /useOperationsCaseRealtime\(caseId/)
})
