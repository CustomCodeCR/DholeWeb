import test from 'node:test'
import assert from 'node:assert/strict'
import { patchPricingPersistedEditAttachments20261030 } from '../build/pricingPersistedEditAttachments20261030.ts'

const fixture = [
  '<script setup lang="ts">',
  "const props = { rateId: 'rate-1', modificationRequestId: null, viewOnly: false }",
  "const editingRate = { value: { shipmentMode: 'Lcl', carrierId: 'legacy-carrier', agentId: 'agent-1', rateDetails: [{ notes: 'Fuente LCL: Coloader' }] } }",
  "const form = { carrierId: '', agentId: 'agent-1' }",
  "const rateLines = { value: [{ detailId: 'saved-1' }] }",
  "const screen7RefreshAllowed = { value: false }",
  'function syncPersistedLinesWithChangedConfiguredCosts() {',
  '  return 12',
  '}',
  'function shouldPreservePersistedEditLines() {',
  '  const rate = editingRate.value',
  '  if (!rate) return false',
  "  return String(rate.carrierId ?? '') === String(form.carrierId ?? '')",
  "    && String(rate.agentId ?? '') === String(form.agentId ?? '')",
  '}',
  '</script>',
  '<template>',
  '<p class="font-black">Documentos de respaldo de la solicitud</p>',
  '<div class="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">',
  '<button type="button" class="font-black text-red-500" @click="removeSupportDocument(document)">Eliminar</button>',
  '</div>',
  '          <div class="grid gap-3 md:grid-cols-3 xl:grid-cols-5">',
  '</div>',
  '</template>',
].join('\n')

function patchedContext() {
  const patched = patchPricingPersistedEditAttachments20261030(fixture)
  const script = patched.split('<script setup lang="ts">')[1]?.split('</script>')[0] ?? ''
  // Parse and execute exactly the JS generated by the late Vite plugin.
  const context = new Function(script + '\nreturn { shouldPreservePersistedEditLines, syncPersistedLinesWithChangedConfiguredCosts, editingRate, form, props, screen7RefreshAllowed };')()
  return { patched, context }
}

test('late Vite transformation emits valid JavaScript for LCL coloader and preserves current prices', () => {
  const { patched, context } = patchedContext()
  assert.match(patched, /const isOwnLcl = \(rate\.rateDetails \?\? \[\]\)\.some/)
  assert.equal(context.shouldPreservePersistedEditLines(), true)
  assert.equal(context.syncPersistedLinesWithChangedConfiguredCosts(), 0)
  context.screen7RefreshAllowed.value = true
  assert.equal(context.syncPersistedLinesWithChangedConfiguredCosts(), 12)
})

test('own LCL and a changed agent do not masquerade as unchanged coloader providers', () => {
  const { context } = patchedContext()
  context.editingRate.value.rateDetails = [{ notes: 'Fuente LCL: Propio' }]
  assert.equal(context.shouldPreservePersistedEditLines(), false)
  context.editingRate.value.rateDetails = [{ notes: 'Fuente LCL: Coloader' }]
  context.form.agentId = 'different-agent'
  assert.equal(context.shouldPreservePersistedEditLines(), false)
})

test('a requested pricing modification preserves the authoritative saved lines', () => {
  const { context } = patchedContext()
  context.props.modificationRequestId = 'modification-1'
  context.editingRate.value.rateDetails = [{ notes: 'Fuente LCL: Propio' }]
  assert.equal(context.shouldPreservePersistedEditLines(), true)
})

test('Screen 4 shows linked files on saved rates and hides upload controls in read-only mode', () => {
  const { patched } = patchedContext()
  assert.match(patched, /v-if="!viewOnly" class="grid gap-3 sm:grid-cols-2 xl:grid-cols-4"/)
  assert.match(patched, /<PricingRateAttachments v-if="editingRate" :rate-id="editingRate.id" :final-documents="finalBackupDocuments" \/>/)
  assert.match(patched, /@click="previewFinalBackup\(document\)"/)
  assert.match(patched, /@click="downloadFinalBackup\(document\)"/)
})
